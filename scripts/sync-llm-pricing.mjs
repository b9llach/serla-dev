// Refresh lib/llm/model-prices.json from LiteLLM's community-maintained
// price map.
//
//   npm run pricing:sync
//
// LiteLLM tracks ~2500 models across every major provider and updates within
// days of a price change - far better than hand-maintaining a table that goes
// stale silently and under-reports customers' spend.
//
// We snapshot rather than fetch at runtime on purpose: cost computation sits
// on the ingest hot path, and it must not depend on a third-party host being
// reachable. Re-run this script (and commit the diff) to pick up new models.

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE =
  'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, '..', 'lib', 'llm', 'model-prices.json');

console.log(`Fetching ${SOURCE}`);
const res = await fetch(SOURCE);
if (!res.ok) {
  console.error(`Failed to fetch pricing data: HTTP ${res.status}`);
  process.exit(1);
}
const raw = await res.json();

/**
 * Output shape: { "<model>": [inputPerMillion, outputPerMillion] }
 *
 * LiteLLM stores per-token costs as tiny floats (2.5e-6). We convert to
 * dollars-per-million so the committed file is human-reviewable and diffs
 * are meaningful.
 */
const prices = {};
let skipped = 0;

for (const [key, entry] of Object.entries(raw)) {
  if (key === 'sample_spec' || !entry || typeof entry !== 'object') continue;
  const input = entry.input_cost_per_token;
  const output = entry.output_cost_per_token;
  if (typeof input !== 'number' || typeof output !== 'number') {
    skipped++;
    continue;
  }
  // Round to 6 decimals of dollars-per-million (i.e. 1e-12 per token) to keep
  // the file compact without losing meaningful precision.
  const round = n => Math.round(n * 1e6 * 1e6) / 1e6;
  prices[key] = [round(input), round(output)];
}

// Index the bare model name too, so `anthropic/claude-sonnet-4-5` and
// `claude-sonnet-4-5` both resolve. Exact keys always win - only fill a
// suffix if nothing claimed it, and skip ambiguous ones where two providers
// disagree on price for the same bare name.
const suffixCandidates = new Map();
for (const [key, value] of Object.entries(prices)) {
  const slash = key.lastIndexOf('/');
  if (slash === -1) continue;
  const bare = key.slice(slash + 1);
  if (!bare || prices[bare]) continue;
  const existing = suffixCandidates.get(bare);
  if (!existing) {
    suffixCandidates.set(bare, value);
  } else if (existing[0] !== value[0] || existing[1] !== value[1]) {
    // Conflicting prices for the same bare name - refuse to guess.
    suffixCandidates.set(bare, null);
  }
}
let aliased = 0;
for (const [bare, value] of suffixCandidates) {
  if (value) {
    prices[bare] = value;
    aliased++;
  }
}

const sorted = Object.fromEntries(
  Object.keys(prices)
    .sort()
    .map(k => [k, prices[k]])
);

const payload = {
  _comment:
    'Generated by scripts/sync-llm-pricing.mjs from LiteLLM. Do not edit by hand. Values are USD per 1M tokens: [input, output].',
  _source: SOURCE,
  _models: Object.keys(sorted).length,
  prices: sorted,
};

writeFileSync(outPath, JSON.stringify(payload, null, 0) + '\n');

console.log(`Priced models: ${Object.keys(sorted).length} (${aliased} bare-name aliases)`);
console.log(`Skipped (no input/output cost): ${skipped}`);
console.log(`Wrote ${outPath}`);
